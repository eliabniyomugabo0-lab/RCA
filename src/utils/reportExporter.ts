  doc.setFillColor(13, 148, 136);
  doc.roundedRect(margin, 20, 48, 48, 8, 8, 'F');
  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.text('GCS', margin + 24, 48, { align: 'center' });

  // Header Titles
