  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(148, 163, 184); // slate-400
  doc.text('Operations Intelligence & Performance Analytics Report', margin + 60, 52);

  doc.setFontSize(8);
  doc.setTextColor(203, 213, 225); // slate-300
  doc.text('Kigali · Rwanda · ICC Accredited International Venue', margin + 60, 66);

